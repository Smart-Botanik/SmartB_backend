export async function seedSiteContent(prisma: PrismaClient) {
  const now = new Date();

  for (const guide of GUIDES) {
    const labelKeys = GUIDE_TAXONOMY_TAG_KEYS_BY_SLUG[guide.slug] ?? [];
    const labelRecords =
      labelKeys.length > 0
        ? await prisma.taxonomyTag.findMany({
            where: { key: { in: labelKeys } },
            select: { id: true },
          })
        : [];

    await prisma.cropGuide.upsert({
      where: { slug: guide.slug },
      update: {
        cropKind: guide.cropKind,
        title: guide.title,
        excerpt: guide.excerpt,
        body: guide.body,
        sortOrder: guide.sortOrder,
        status: ContentStatus.PUBLISHED,
        publishedAt: now,
        seoTitle: `${guide.title} — SmartБотаник`,
        seoDescription: guide.excerpt,
        taxonomyTags: { set: labelRecords.map(tag => ({ id: tag.id })) },
      },
      create: {
        cropKind: guide.cropKind,
        slug: guide.slug,
        title: guide.title,
        excerpt: guide.excerpt,
        body: guide.body,
        sortOrder: guide.sortOrder,
        status: ContentStatus.PUBLISHED,
        publishedAt: now,
        seoTitle: `${guide.title} — SmartБотаник`,
        seoDescription: guide.excerpt,
        taxonomyTags: { connect: labelRecords.map(tag => ({ id: tag.id })) },
      },
    });
  }

  await prisma.sitePage.upsert({
    where: { key: "home" },
    update: {
      title: "SmartБотаник — главная",
      sections: HOME_SECTIONS,
      status: ContentStatus.PUBLISHED,
      publishedAt: now,
      seoTitle: "SmartБотаник — советы по выращиванию",
      seoDescription:
        "Руководства по помидорам, огурцам, кабачкам и баклажанам.",
    },
    create: {
      key: "home",
      title: "SmartБотаник — главная",
      sections: HOME_SECTIONS,
      status: ContentStatus.PUBLISHED,
      publishedAt: now,
      seoTitle: "SmartБотаник — советы по выращиванию",
      seoDescription:
        "Руководства по помидорам, огурцам, кабачкам и баклажанам.",
    },
  });

  return {
    guides: GUIDES.length,
    sitePages: 1,
    status: ContentStatus.PUBLISHED,
  };
}
